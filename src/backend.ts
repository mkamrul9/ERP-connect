/**
 * Extracts a clean client IP address from a request, handling reverse-proxy headers
 * (Cloudflare, nginx, Render) and normalising IPv6-mapped IPv4 addresses.
 */
export function getCleanClientIp(req: express.Request): string {
  const forwarded =
    req.headers['x-forwarded-for'] ||
    req.headers['x-real-ip'] ||
    req.headers['cf-connecting-ip'];

  let rawIp = '';
  if (typeof forwarded === 'string') {
    rawIp = (forwarded.split(',')[0] || '').trim();
  } else if (Array.isArray(forwarded) && forwarded.length > 0) {
    rawIp = String(forwarded[0] || '').trim();
  } else {
    rawIp = req.socket?.remoteAddress || '';
  }

  // Normalise IPv6-mapped IPv4 (::ffff:1.2.3.4 → 1.2.3.4)
  if (rawIp.startsWith('::ffff:')) rawIp = rawIp.substring(7);
  if (!rawIp || rawIp === '::1') rawIp = '127.0.0.1';

  return rawIp;
}

/**
 * Returns `true` if `clientIp` matches any entry in a comma-separated list of
 * allowed IP addresses/prefixes (supports `*` wildcard suffix and trailing `.`).
 */
export function isIpMatching(clientIp: string, allowedIpsStr: string): boolean {
  if (!clientIp || !allowedIpsStr) return false;
  const list = allowedIpsStr.split(',').map(s => s.trim().toLowerCase()).filter(Boolean);
  const clean = clientIp.toLowerCase();
  for (const item of list) {
    if (item === clean) return true;
    if (
      (item === '127.0.0.1' || item === '::1' || item === 'localhost') &&
      (clean === '127.0.0.1' || clean === '::1')
    ) return true;
    if (item.endsWith('*') && clean.startsWith(item.slice(0, -1))) return true;
    if (item.endsWith('.') && clean.startsWith(item)) return true;
  }
  return false;
}

/**
 * Parses a database date value (string or Date) into a JavaScript `Date`,
 * correctly handling both PostgreSQL UTC ISO strings and SQLite datetime strings.
 */
export function parseDbDate(raw: string | Date): Date {
  if (!raw) return new Date();
  if (raw instanceof Date) return raw;
  let s = String(raw).trim();
  if (s.endsWith('Z') || s.includes('+') || (s.includes('-') && s.lastIndexOf('-') > 10)) {
    return new Date(s);
  }
  if (s.includes('T')) return new Date(s + 'Z');
  return new Date(s.replace(' ', 'T') + 'Z');
}

