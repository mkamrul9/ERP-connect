/**
 * Inserts an in-app notification for a single member.
 * Email notifications are handled separately via Brevo routes.
 */
async function notifyMember(memberId: number, message: string, link = '') {
  await dbRun(
    `INSERT INTO notifications(member_id, message, link) VALUES (?, ?, ?)`,
    [memberId, message, link],
  );
}

/**
 * Inserts an in-app notification for every Admin member.
 */
async function notifyAdmins(message: string, link = '') {
  const admins = await dbAll(`SELECT id FROM members WHERE role = 'Admin'`) as any[];
  for (const admin of admins) {
    await dbRun(
      `INSERT INTO notifications(member_id, message, link) VALUES (?, ?, ?)`,
      [admin.id, message, link],
    );
  }
}

/**
 * Formats reminder offset parts (days / hours / minutes) into a human-readable string,
 * e.g. `"2 day(s), 30 minute(s)"`.
 */
function formatReminderLabel(
  days?: number | null,
  hours?: number | null,
  minutes?: number | null,
): string {
  const parts: string[] = [];
  if (Number(days)    > 0) parts.push(`${Number(days)} day(s)`);
  if (Number(hours)   > 0) parts.push(`${Number(hours)} hour(s)`);
  if (Number(minutes) > 0) parts.push(`${Number(minutes)} minute(s)`);
  return parts.join(', ');
}

/**
 * Creates an in-app notification for Admins when a reminder is configured on an entity.
 * Also notifies the associated member if they are not an Admin.
 */
async function notifyReminderConfigured(params: {
  entityLabel: string;
  title: string;
  link: string;
  remDays?: number | null;
  remHours?: number | null;
  remMins?: number | null;
  alsoMemberId?: number | null;
}) {
  const label = formatReminderLabel(params.remDays, params.remHours, params.remMins);
  if (!label) return;

  const msg = `Reminder set for ${params.entityLabel}: "${params.title}" (${label} before).`;
  await notifyAdmins(msg, params.link);

  if (params.alsoMemberId) {
    const member = await dbGet(`SELECT role FROM members WHERE id = ?`, [params.alsoMemberId]) as any;
    if (member && member.role !== 'Admin') {
      await dbRun(
        `INSERT INTO notifications(member_id, message, link) VALUES (?, ?, ?)`,
        [params.alsoMemberId, msg, params.link],
      );
    }
  }
}

