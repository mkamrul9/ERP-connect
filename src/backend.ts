/**
 * src/backend.ts
 *
 * Express API server for ERP-connect.
 *
 * Architecture: All API routes are mounted inside a single async factory function
 * `createBackendApp()`. This is called once by `server.ts` which then attaches
 * the Next.js request handler for the frontend. The two apps share a single
 * HTTP port (default 3000, overridden by the PORT env variable).
 *
 * Notification channel: Email only (via Brevo / `src/brevo.ts`).
 *   All Telegram and WhatsApp integrations have been removed.
 *
 * Authentication: JWT-based bearer tokens + HTTP-only cookie fallback.
 *   Tokens are signed with JWT_SECRET (auto-generated by Render or set manually).
 *   Rate-limiting is applied to the login endpoint (10 attempts / 15 min / IP).
 *
 * Database: Dual-mode via `src/db.ts` — SQLite for local dev, PostgreSQL for
 *   production (triggered by the DATABASE_URL environment variable).
 *
 * @module backend
 */

